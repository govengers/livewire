// Options configures Write. TypeScriptDirectory receives types.ts, filters.ts, api.ts,
// runtime.ts and vue.ts ("" writes no TypeScript); OpenAPIFile is the path of the OpenAPI
// 3.0.3 document ("" writes none), a YAML file whose content is JSON under the generated
// header (YAML reads JSON, and a JSON file could not carry the header), so it must not end in
// ".json". GoClient configures the Go client package and CommandLine the command-line client
// (each written only with its Directory). At least one output is required. OpenAPI describes
// the document and is required with OpenAPIFile.
//
// Enums names the values of named string types: reflection cannot list a Go type's
// constants, and an `enum:"a,b"` tag on every field repeats the list, so a named string type
// listed here is a union of its values in TypeScript and an enum in OpenAPI wherever it
// appears; an `enum` tag on a field still wins for that field. Presence says that the
// engine serves presence (EngineOptions.PresenceStore is set, D37): only then are the
// presence reads, their routes and joins generated, as only then does the REST adapter
// mount them.
type Options struct {
	TypeScriptDirectory string
	OpenAPIFile         string
	OpenAPI             OpenAPIOptions
	GoClient            GoClientOptions
	CommandLine         CommandLineOptions
	Enums               []Enum
	Presence            bool
}

// GoClientOptions configures the Go client package (D19, D67), written into Directory as
// client.go and filters.go ("" writes none). ImportPath is that directory's import path,
// required with it: the client imports the application's DTO packages, so Write refuses a
// type the package could not import from there (an unexported one, one of a main or test
// package, one behind an internal directory whose parent does not contain ImportPath). Package
// is the package name, by default the last element of ImportPath ("partsclient").
type GoClientOptions struct {
	Directory  string
	ImportPath string
	Package    string
}

// CommandLineOptions configures the command-line client on github.com/urfave/cli/v3 (D19,
// D20), written into Directory as command.go ("" writes none): a package whose Command is the
// root command and whose Run is a binary's main. Name is the command's name (required,
// lower-case letters, digits and dashes); EnvironmentPrefix prefixes its environment
// variables <PREFIX>_BASE_URL, <PREFIX>_API_KEY and <PREFIX>_SOCKET_URL (default: Name
// upper-cased with dashes as underscores); Package is the package name, by default the last
// element of Directory. The CLI imports no DTO package: it passes the JSON through.
type CommandLineOptions struct {
	Directory         string
	Package           string
	Name              string
	EnvironmentPrefix string
}

// OpenAPIOptions describes the OpenAPI document: its info (Title and Version are required),
// its servers, whose URLs stop before the registry's BasePath (the paths carry it), and the
// security schemes every operation accepts, any one of them (D20: an API key for the CLI and
// the Go client next to the browser's session, for instance).
type OpenAPIOptions struct {
	Title           string
	Version         string
	Description     string
	Servers         []Server
	SecuritySchemes []SecurityScheme
}

// Server is one entry of the document's servers.
type Server struct {
	URL         string
	Description string
}

// SecurityScheme is one entry of components.securitySchemes: Name is its key, Type one of
// "http" (with Scheme, "bearer" or "basic", and an optional BearerFormat), "apiKey" (with In,
// "header", "query" or "cookie", and ParameterName) or "openIdConnect" (with
// OpenIDConnectURL).
type SecurityScheme struct {
	Name             string
	Type             string
	Description      string
	Scheme           string
	BearerFormat     string
	In               string
	ParameterName    string
	OpenIDConnectURL string
}

// Enum lists the values of a named string type; build it with EnumOf.
type Enum struct {
	Type   reflect.Type
	Values []string
}

// EnumOf lists the values of the named string type Value, in the order the generated union
// and the OpenAPI enum show them.
func EnumOf[Value ~string](values ...Value) Enum {
	enum := Enum{Type: reflect.TypeFor[Value](), Values: make([]string, 0, len(values))}
	for _, value := range values {
		enum.Values = append(enum.Values, string(value))
	}
	return enum
}

// header heads every generated file, in the file's comment syntax.
const header = "Code generated by livewire. DO NOT EDIT."

// Write generates the artifacts of the registry into the files the options name. It
// validates and copies the options (DES-001), renders every file before it writes the first,
// so a registry the generator cannot describe writes nothing, and creates the TypeScript
// directory and the OpenAPI file's directory as needed. It fails on a Go type encoding/json
// cannot marshal (a channel, a function, a complex number, a map with keys of another kind
// than string, integer or encoding.TextMarshaler), on two generated TypeScript identifiers
// that collide (two declaration names that differ only in the case of their first letter,
// say) or that are reserved words, and on invalid options. Two DTOs with the same Go name
// from different packages never collide: both are qualified with their package's name,
// deterministically. With a Go client it also fails on a type the client cannot import from
// GoClient.ImportPath (D67), on a ClientID create whose body's id it cannot fill in, and on
// two Go identifiers that collide; with a CLI on two commands or flags of one command that
// share a name (D68).
func Write(registry *livewire.Registry, options *Options) error {
	if registry == nil {
		return errors.New("generate: Write needs a registry")
	}
	files, err := Render(registry, options)
	if err != nil {
		return err
	}
	for _, file := range files {
		if err := os.MkdirAll(filepath.Dir(file.Path), 0o750); err != nil {
			return fmt.Errorf("generate: %w", err)
		}
		if err := os.WriteFile(file.Path, file.Content, 0o600); err != nil {
			return fmt.Errorf("generate: %w", err)
		}
	}
	return nil
}

// File is one artifact as Render renders it: the path the options give it and its content.
type File struct {
	Path    string
	Content []byte
}

// Render renders every file Write would write, with the same validation and refusals, and
// writes nothing: the paths are the ones the options name, so a test compares each with the
// committed file at that path (livewiretest.GeneratedIsCurrent, D70).
func Render(registry *livewire.Registry, options *Options) ([]File, error) {
	if registry == nil {
		return nil, errors.New("generate: Render needs a registry")
	}
	resolved, err := resolveOptions(options)
	if err != nil {
		return nil, err
	}
	files, err := render(registry, resolved)
	if err != nil {
		return nil, err
	}
	rendered := make([]File, len(files))
	for index, file := range files {
		rendered[index] = File{Path: file.path, Content: file.content}
	}
	return rendered, nil
}

// file is one rendered artifact.
type file struct {
	path    string
	content []byte
}

// render builds the model of the registry and renders every artifact the options ask for.
// The TypeScript is rendered either way: its identifiers are the OpenAPI operation ids too,
// so a collision fails the document as well.
func render(registry *livewire.Registry, options Options) ([]file, error) {
	model, err := newModel(registry, options)
	if err != nil {
		return nil, err
	}
	typescriptFiles, err := renderTypeScript(model)
	if err != nil {
		return nil, err
	}
	goFiles, err := renderGo(model, options)
	if err != nil {
		return nil, err
	}
	files := goFiles
	if options.TypeScriptDirectory != "" {
		for _, typescriptFile := range typescriptFiles {
			files = append(files, file{path: filepath.Join(options.TypeScriptDirectory, typescriptFile.path), content: typescriptFile.content})
		}
	}
	if options.OpenAPIFile != "" {
		document, err := renderOpenAPI(model, options.OpenAPI)
		if err != nil {
			return nil, err
		}
		files = append(files, file{path: options.OpenAPIFile, content: document})
	}
	return files, nil
}

func resolveOptions(options *Options) (Options, error) {
	if options == nil {
		return Options{}, errors.New("generate: Write needs options")
	}
	resolved := *options
	resolved.Enums = slices.Clone(options.Enums)
	resolved.OpenAPI.Servers = slices.Clone(options.OpenAPI.Servers)
	resolved.OpenAPI.SecuritySchemes = slices.Clone(options.OpenAPI.SecuritySchemes)
	switch {
	case resolved.TypeScriptDirectory == "" && resolved.OpenAPIFile == "" && resolved.GoClient.Directory == "" && resolved.CommandLine.Directory == "":
		return Options{}, errors.New("generate: Options needs a TypeScriptDirectory, an OpenAPIFile, a GoClient.Directory or a CommandLine.Directory")
	case strings.HasSuffix(strings.ToLower(resolved.OpenAPIFile), ".json"):
		return Options{}, fmt.Errorf("generate: OpenAPIFile %q: the document is YAML under a header comment; name it .yaml", resolved.OpenAPIFile)
	}
	for position := range resolved.Enums {
		enum := &resolved.Enums[position]
		enum.Values = slices.Clone(enum.Values)
		if err := validateEnum(*enum, resolved.Enums[:position]); err != nil {
			return Options{}, err
		}
	}
	if resolved.OpenAPIFile != "" {
		if err := validateOpenAPI(resolved.OpenAPI); err != nil {
			return Options{}, err
		}
	}
	if err := resolveGoClient(&resolved.GoClient); err != nil {
		return Options{}, err
	}
	if err := resolveCommandLine(&resolved.CommandLine); err != nil {
		return Options{}, err
	}
	return resolved, nil
}

func validateEnum(enum Enum, earlier []Enum) error {
	switch {
	case enum.Type == nil || enum.Type.Kind() != reflect.String || enum.Type.PkgPath() == "":
		return fmt.Errorf("generate: Enums: %v is not a named string type", enum.Type)
	case len(enum.Values) == 0:
		return fmt.Errorf("generate: Enums: %v has no values", enum.Type)
	case marshalsItselfAnyway(enum.Type):
		return fmt.Errorf("generate: Enums: %v marshals itself, so its values cannot describe its JSON", enum.Type)
	case slices.ContainsFunc(earlier, func(other Enum) bool { return other.Type == enum.Type }):
		return fmt.Errorf("generate: Enums: %v is listed twice", enum.Type)
	}
	for position, value := range enum.Values {
		if slices.Contains(enum.Values[:position], value) {
			return fmt.Errorf("generate: Enums: %v lists %q twice", enum.Type, value)
		}
	}
	return nil
}

func validateOpenAPI(options OpenAPIOptions) error {
	if options.Title == "" || options.Version == "" {
		return errors.New("generate: OpenAPI needs a Title and a Version")
	}
	for _, server := range options.Servers {
		if server.URL == "" {
			return errors.New("generate: OpenAPI.Servers: every server needs a URL")
		}
	}
	var names []string
	for _, scheme := range options.SecuritySchemes {
		if scheme.Name == "" || slices.Contains(names, scheme.Name) {
			return fmt.Errorf("generate: OpenAPI.SecuritySchemes: the name %q is empty or repeated", scheme.Name)
		}
		names = append(names, scheme.Name)
		if err := validateSecurityScheme(scheme); err != nil {
			return err
		}
	}
	return nil
}

func validateSecurityScheme(scheme SecurityScheme) error {
	var complete bool
	switch scheme.Type {
	case "http":
		complete = scheme.Scheme != ""
	case "apiKey":
		complete = slices.Contains([]string{"header", "query", "cookie"}, scheme.In) && scheme.ParameterName != ""
	case "openIdConnect":
		complete = scheme.OpenIDConnectURL != ""
	default:
		return fmt.Errorf("generate: OpenAPI.SecuritySchemes: %q has the type %q, not http, apiKey or openIdConnect", scheme.Name, scheme.Type)
	}
	if !complete {
		return fmt.Errorf("generate: OpenAPI.SecuritySchemes: %q of type %s lacks its Scheme, In and ParameterName, or OpenIDConnectURL", scheme.Name, scheme.Type)
	}
	return nil
}
