func TestOpenAPIDocumentValidates(t *testing.T) {
	directory := generateFixture(t)
	loader := openapi3.NewLoader()
	document, err := loader.LoadFromFile(filepath.Join(directory, "openapi.yaml"))
	require.NoError(t, err)
	require.NoError(t, document.Validate(context.Background()))
	require.Equal(t, "3.0.3", document.OpenAPI)

	for _, path := range []string{
		"/api/v1/parts", "/api/v1/parts/{id}", "/api/v1/parts/distinct", "/api/v1/parts/{id}/history", "/api/v1/parts/presence",
		"/api/v1/parts/export", "/api/v1/notes", "/api/v1/boards/{board}/stats", "/api/v1/labels", "/api/v1/boards/{board}/dashboard",
		"/api/v1/boards/{board}/dashboard/presence", "/api/v1/parts/{id}/attachments", "/api/v1/billing/charges", "/api/v1/rebuild",
		"/api/v1/batch", "/api/v1/filters", "/api/v1/filters/{id}",
	} {
		require.NotNil(t, document.Paths.Find(path), path)
	}
	parts := document.Paths.Find("/api/v1/parts")
	require.Equal(t, map[string]any{"target": "parts", "ops": []any{"query", "subscribe"}}, parts.Get.Extensions["x-websocket"])
	require.Equal(t, "#/components/schemas/FixturePartListResponse", parts.Get.Responses.Status(http.StatusOK).Value.Content["application/json"].Schema.Ref)
	require.Equal(t, map[string]any{"target": "createPart", "ops": []any{"call"}}, parts.Post.Extensions["x-websocket"])
	require.NotNil(t, parts.Post.Responses.Status(http.StatusCreated).Value.Content["application/json"])
	require.Equal(t, "#/components/schemas/PartsFilter", parts.Get.Parameters.GetByInAndName("query", "filter").Content["application/json"].Schema.Ref)
	require.Equal(t, []any{"query"}, document.Paths.Find("/api/v1/notes").Get.Extensions["x-websocket"].(map[string]any)["ops"], "notes is not live")
	presence := document.Paths.Find("/api/v1/parts/presence").Get.Extensions["x-websocket"].(map[string]any)
	require.Equal(t, []any{"query", "subscribe", "join", "leave"}, presence["ops"])

	deletion := document.Paths.Find("/api/v1/parts/{id}").Delete
	require.Nil(t, deletion.Responses.Status(http.StatusNoContent).Value.Content)
	require.NotNil(t, deletion.Parameters.GetByInAndName("header", "Idempotency-Key"))

	upload := document.Paths.Find("/api/v1/parts/{id}/attachments").Post.RequestBody.Value.Content
	require.ElementsMatch(t, []string{"image/png", "image/jpeg", "multipart/form-data"}, slices.Collect(keys(upload)))
	require.Equal(t, "binary", upload["image/png"].Schema.Value.Format)
	export := document.Paths.Find("/api/v1/parts/export").Get.Responses.Status(http.StatusOK).Value
	require.NotNil(t, export.Content["text/csv"])
	require.Contains(t, *export.Description, ginadapter.ExportRowsTrailer)

	schemas := document.Components.Schemas
	part := schemas["FixturePart"].Value
	require.True(t, part.Properties["price"].Value.Nullable, "a pointer is nullable: true, never anyOf null (D26)")
	require.Equal(t, true, part.Properties["secret"].Value.Extensions["x-livewire-guarded"])
	require.NotContains(t, part.Required, "secret", "a guarded field is optional (D39)")
	require.NotContains(t, part.Required, "ownerId", "a field promoted through an embedded pointer is left out with it")
	require.Contains(t, part.Required, "started", "omitempty never omits a struct")
	require.True(t, part.Properties["updatedAt"].Value.Nullable)
	require.Equal(t, []any{"invalid_request", "invalid_filter", "invalid_sort", "invalid_page", "invalid_cursor", "forbidden_field", "unauthenticated", "forbidden", "not_found", "conflict", "in_progress", "internal"}, schemas["ErrorCode"].Value.Enum)
	require.Equal(t, []any{"bolt", "nut"}, schemas["Kind"].Value.Enum)
	require.NotNil(t, schemas["FixturePartVersionListResponse"])
	require.NotNil(t, schemas["HistoryFilter"])
	require.NotNil(t, schemas["PartsFilterNode"])
	require.Len(t, document.Security, 2)
	require.Equal(t, "cookie", document.Components.SecuritySchemes["session"].Value.In)
}

func keys[Value any](values map[string]Value) func(func(string) bool) {
	return func(yield func(string) bool) {
		for key := range values {
			if !yield(key) {
				return
			}
		}
	}
}

// TestMappingFollowsEncodingJSON pins every mapping rule in the generated FixturePart.
func TestMappingFollowsEncodingJSON(t *testing.T) {
	types := readGenerated(t, generateFixture(t), "typescript/types.ts")
	_, part, found := strings.Cut(types, "export interface FixturePart {")
	require.True(t, found)
	part, _, _ = strings.Cut(part, "\n}\n")
	for _, line := range []string{
		"createdAt: string",                       // an embedded struct is flattened; time.Time is a string
		"updatedAt: string | null",                // a pointer is nullable
		"ownerId?: string",                        // promoted through an embedded pointer: absent while it is nil
		"promoted: string",                        // promoted through an unexported embedding
		"dimensions: Dimensions",                  // an embedding with a JSON name is one field
		"id: string",                              // uuid.UUID is a string
		"kind: Kind",                              // a listed named string type
		"color: Color",                            // an unlisted named string type, an alias of string
		"secret?: string",                         // guarded (D39)
		"notes?: string",                          // omitempty
		"previous?: Kind",                         // omitempty on a pointer: present, not null
		"tags: Tags | null",                       // a named slice is nullable
		"labels?: string[]",                       // omitempty on a slice: present, not null
		"sizes: ('s' | 'm' | 'l')[] | null",       // an enum tag on a slice
		"grade: 'a' | 'b'",                        // an enum tag
		"counts: Record<string, number> | null",   // a map is nullable
		"names?: Record<string, string>",          // omitzero; integer keys are strings
		"children: (FixturePart | null)[] | null", // pointer elements are nullable
		"matrix: number[]",                        // an array is never null
		"checksum: string | null",                 // []byte is base64
		"total: Cents",                            // a named number
		"large: string",                           // the string option
		"flag: string | null",                     // the string option behind a pointer
		"expires?: string",                        // omitzero on a struct
		"started: string",                         // omitempty never omits a struct
		"extra: unknown",                          // json.RawMessage
		"anything: unknown",                       // an interface
		"payload: unknown",                        // a json.Marshaler
		"code: string",                            // an encoding.TextMarshaler
		`"content-type": string`,                  // a key that is no identifier
		`"-": string`,                             // json:"-,"
		"inline: { A: number }",                   // an anonymous struct
	} {
		require.Contains(t, part, "\n  "+line+"\n", line)
	}
	require.NotContains(t, part, "Skipped")
	require.NotContains(t, part, "unexported")
	require.Contains(t, types, "export type Kind = 'bolt' | 'nut'\n")
	require.Contains(t, types, "export interface Node {\n  name: string\n  children: Node[] | null\n}\n", "a recursive type refers to itself")
	require.Contains(t, types, "export interface PageNode {", "a generic type is named after its argument")
	require.Contains(t, types, "export interface Stat {\n  id: string\n  name: string\n  hits?: number\n}\n", "a typed list's guarded field is optional")
}

