func TestGeneratorRefusals(t *testing.T) {
	list := func(name string, item func() livewire.Declaration) *livewire.Registry {
		registry, err := livewire.NewRegistry(nil)
		require.NoError(t, err)
		require.NoError(t, registry.Add(item()), name)
		return registry
	}
	testCases := []struct {
		name     string
		registry *livewire.Registry
		message  string
	}{
		{"a channel", list("channel", func() livewire.Declaration {
			return livewire.NewList("items", "/items", &livewire.ListOptions[unsupportedItem, livewire.NoParameters]{
				Read: authorization.IsUser(), Load: func(context.Context, *livewire.NoParameters) ([]unsupportedItem, error) { return nil, nil },
			})
		}), "cannot marshal the type chan int"},
		{"a map key", list("map", func() livewire.Declaration {
			return livewire.NewList("items", "/items", &livewire.ListOptions[unsupportedMap, livewire.NoParameters]{
				Read: authorization.IsUser(), Load: func(context.Context, *livewire.NoParameters) ([]unsupportedMap, error) { return nil, nil },
			})
		}), "its key is no string"},
		{"a reserved word", list("reserved", func() livewire.Declaration {
			return livewire.NewMutation("delete", http.MethodPost, "/delete", &livewire.MutationOptions[livewire.NoParameters, livewire.NoBody, livewire.NoContent]{
				Check: authorization.IsUser(), Handle: func(context.Context, *livewire.NoParameters, *livewire.NoBody) (*livewire.NoContent, error) {
					return &livewire.NoContent{}, nil
				},
			})
		}), "a reserved word"},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			directory := t.TempDir()
			options := &generate.Options{TypeScriptDirectory: directory, OpenAPIFile: filepath.Join(directory, "openapi.yaml"), OpenAPI: generate.OpenAPIOptions{Title: "x", Version: "1"}}
			require.ErrorContains(t, generate.Write(testCase.registry, options), testCase.message)
		})
	}
}

