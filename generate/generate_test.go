func readGenerated(t *testing.T, directory, name string) string {
	t.Helper()
	return string(readFile(t, filepath.Join(directory, name)))
}

// readFile reads a file the test generated or one of its fixtures.
func readFile(t *testing.T, path string) []byte {
	t.Helper()
	content, err := os.ReadFile(path) //nolint:gosec // G304: the test's own temporary files and fixtures
	require.NoError(t, err)
	return content
}

// writeFile writes a file below a test's temporary directory or the golden directory.
func writeFile(t *testing.T, path string, content []byte) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o750))
	require.NoError(t, os.WriteFile(path, content, 0o600))
}

