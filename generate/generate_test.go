// TestIndistinguishableNamesAreNumbered declares two types of one package and one name (local
// to two scopes): no qualification tells them apart, the order they are reached in does.
func TestIndistinguishableNamesAreNumbered(t *testing.T) {
	registry, err := livewire.NewRegistry(nil)
	require.NoError(t, err)
	type Item struct {
		A string `json:"a"`
	}
	first := livewire.NewMutation("first", http.MethodPost, "/first", &livewire.MutationOptions[livewire.NoParameters, livewire.NoBody, Item]{
		Check: authorization.IsUser(), Handle: func(context.Context, *livewire.NoParameters, *livewire.NoBody) (*Item, error) { return &Item{}, nil },
	})
	{
		type Item struct {
			B string `json:"b"`
		}
		second := livewire.NewMutation("second", http.MethodPost, "/second", &livewire.MutationOptions[livewire.NoParameters, livewire.NoBody, Item]{
			Check: authorization.IsUser(), Handle: func(context.Context, *livewire.NoParameters, *livewire.NoBody) (*Item, error) { return &Item{}, nil },
		})
		require.NoError(t, registry.Add(first, second))
	}
	directory := t.TempDir()
	require.NoError(t, generate.Write(registry, &generate.Options{TypeScriptDirectory: directory}))
	types := readGenerated(t, directory, "types.ts")
	require.Contains(t, types, "export interface Item {\n  a: string\n}")
	require.Contains(t, types, "export interface Item2 {\n  b: string\n}")
}

func TestOptionsAreValidated(t *testing.T) {
	registry := newRegistry(t)
	directory := t.TempDir()
	valid := func() *generate.Options { return fixtureOptions(directory) }
	testCases := []struct {
		name    string
		options func() *generate.Options
		message string
	}{
		{"nil options", func() *generate.Options { return nil }, "needs options"},
		{"no output", func() *generate.Options { return &generate.Options{} }, "TypeScriptDirectory, an OpenAPIFile or both"},
		{"a JSON file", func() *generate.Options { options := valid(); options.OpenAPIFile = "openapi.json"; return options }, "name it .yaml"},
		{"no title", func() *generate.Options { options := valid(); options.OpenAPI.Title = ""; return options }, "Title and a Version"},
		{"a server without URL", func() *generate.Options {
			options := valid()
			options.OpenAPI.Servers = []generate.Server{{}}
			return options
		}, "needs a URL"},
		{"a repeated scheme", func() *generate.Options {
			options := valid()
			options.OpenAPI.SecuritySchemes = append(options.OpenAPI.SecuritySchemes, options.OpenAPI.SecuritySchemes[0])
			return options
		}, "empty or repeated"},
		{"an unknown scheme type", func() *generate.Options {
			options := valid()
			options.OpenAPI.SecuritySchemes = []generate.SecurityScheme{{Name: "x", Type: "oauth2"}}
			return options
		}, "not http, apiKey or openIdConnect"},
		{"an incomplete scheme", func() *generate.Options {
			options := valid()
			options.OpenAPI.SecuritySchemes = []generate.SecurityScheme{{Name: "x", Type: "apiKey", In: "header"}}
			return options
		}, "lacks"},
		{"an enum of no named string", func() *generate.Options {
			options := valid()
			options.Enums = []generate.Enum{{Type: reflect.TypeFor[int](), Values: []string{"a"}}}
			return options
		}, "not a named string type"},
		{"an enum without values", func() *generate.Options {
			options := valid()
			options.Enums = []generate.Enum{generate.EnumOf[fixture.Kind]()}
			return options
		}, "has no values"},
		{"an enum listed twice", func() *generate.Options {
			options := valid()
			options.Enums = append(options.Enums, options.Enums[0])
			return options
		}, "listed twice"},
		{"an enum value listed twice", func() *generate.Options {
			options := valid()
			options.Enums = []generate.Enum{generate.EnumOf(fixture.KindBolt, fixture.KindBolt)}
			return options
		}, `lists "bolt" twice`},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			err := generate.Write(registry, testCase.options())
			require.ErrorContains(t, err, testCase.message)
		})
	}
	require.ErrorContains(t, generate.Write(nil, valid()), "needs a registry")
	entries, err := os.ReadDir(directory)
	require.NoError(t, err)
	require.Empty(t, entries, "a refused Write writes nothing")
}

